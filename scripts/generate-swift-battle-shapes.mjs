#!/usr/bin/env node
//
// Writes ios/Packages/GameRules/Sources/GameRules/BattleShapes.swift from the
// battle-grid shape library in src/data/battleShapes.js, so the Swift port
// carries the same shapes, in the same order, without hand-copying 40 ASCII
// grids. Re-run whenever battleShapes.js changes:
//
//   npm run ios:battle-shapes
//
// Deterministic. BattleLayoutTests in GameRules compares the Swift shapes to
// golden/battle-problems.json, so a shape edited in JS but not regenerated here
// fails the Swift tests once the golden files are regenerated.

import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { BATTLE_SHAPES } from '../src/data/battleShapes.js';

const OUT = resolve(
  dirname(fileURLToPath(import.meta.url)),
  '..', 'ios', 'Packages', 'GameRules', 'Sources', 'GameRules', 'BattleShapes.swift',
);

// JSON string escaping is valid Swift string-literal escaping for the
// characters that can appear here (quotes, backslashes, newlines).
const swiftString = value => JSON.stringify(value);

const entries = Object.entries(BATTLE_SHAPES).map(([id, shape]) => {
  const art = shape.art.split('\n').map(line => `            ${line}`).join('\n');
  return [
    '        BattleShape(',
    `            id: ${swiftString(id)}, name: ${swiftString(shape.name)},`,
    `            cells: ${shape.cells}, width: ${shape.width}, height: ${shape.height},`,
    '            art: """',
    art,
    '            """',
    '        ),',
  ].join('\n');
});

const source = `// GENERATED by scripts/generate-swift-battle-shapes.mjs from
// src/data/battleShapes.js — do not edit by hand. Run
// \`npm run ios:battle-shapes\` after changing the JavaScript shapes.

extension BattleShape {
    /// Every shape in the library, in the JavaScript \`BATTLE_SHAPES\` order.
    public static let all: [BattleShape] = [
${entries.join('\n')}
    ]
}
`;

writeFileSync(OUT, source);
console.log(`wrote ${OUT}`);
