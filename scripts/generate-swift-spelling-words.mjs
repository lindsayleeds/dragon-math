#!/usr/bin/env node
//
// Writes ios/Packages/GameRules/Sources/GameRules/SpellingWords.swift from the
// Dragon Spelling catalogs in src/data/spellingWords.js — every grade's words
// in catalog order (the order a round's shuffle starts from), the words per
// round, and which words are spoken with an example sentence (their clip is
// public/audio/spelling/prompts/<word>.mp3, not <word>.mp3) — so the app plays
// the same rounds offline without hand-copying 600 words. Re-run whenever
// spellingWords.js or spellingPrompts.js changes:
//
//   npm run ios:spelling-words
//
// Deterministic. src/data/spellingWords.swift.test.js renders the file again
// and fails when the committed Swift file is stale.

import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  SPELLING_GRADES,
  SPELLING_WORDS,
  WORDS_PER_ROUND,
  gradeSource,
} from '../src/data/spellingWords.js';

export const SWIFT_SPELLING_WORDS_PATH = resolve(
  dirname(fileURLToPath(import.meta.url)),
  '..', 'ios', 'Packages', 'GameRules', 'Sources', 'GameRules', 'SpellingWords.swift',
);

// JSON string escaping is valid Swift string-literal escaping for these
// (lowercase single-token words and short labels).
const str = value => JSON.stringify(value);

// Ten words to a line, like spellingWords.js.
function wordLines(words, indent) {
  const lines = [];
  for (let i = 0; i < words.length; i += 10) {
    lines.push(`${indent}${words.slice(i, i + 10).map(str).join(', ')},`);
  }
  return lines.join('\n');
}

export function renderSwiftSpellingWords() {
  const grades = SPELLING_GRADES.map(({ grade, label }) => [
    `        SpellingGrade(grade: ${grade}, label: ${str(label)}, words: [`,
    wordLines(SPELLING_WORDS[grade] || [], '            '),
    '        ]),',
  ].join('\n'));

  // Only grade words with a sentence matter here: the app plays grade
  // catalogs, and a word's sentence decides which bundled clip it has.
  const catalogWords = new Set(Object.values(SPELLING_WORDS).flat());
  const promptWords = Object.keys(gradeSource(1).exampleSentences)
    .filter(word => catalogWords.has(word))
    .sort();

  return `// GENERATED by scripts/generate-swift-spelling-words.mjs from
// src/data/spellingWords.js and spellingPrompts.js — do not edit by hand. Run
// \`npm run ios:spelling-words\` after changing the JavaScript catalogs.

extension SpellingGrade {
    /// Every grade, in the JavaScript \`SPELLING_GRADES\` order, with its words
    /// in \`SPELLING_WORDS\` order.
    public static let all: [SpellingGrade] = [
${grades.join('\n')}
    ]
}

extension Spelling {
    /// Words a grade round plays (\`WORDS_PER_ROUND\`).
    public static let wordsPerRound = ${WORDS_PER_ROUND}

    /// Grade words recorded with an example sentence (the keys of
    /// \`SPELLING_EXAMPLE_SENTENCES\` that are in a catalog): their clip is the
    /// word, the sentence, the word — \`prompts/<word>.mp3\`.
    public static let promptWords: Set<String> = [${promptWords.map(str).join(', ')}]
}
`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writeFileSync(SWIFT_SPELLING_WORDS_PATH, renderSwiftSpellingWords());
  console.log(`wrote ${SWIFT_SPELLING_WORDS_PATH}`);
}
