#!/usr/bin/env node
//
// Writes ios/Packages/GameRules/Sources/GameRules/LairCatalog.swift from the
// Learning Lair catalog in src/data/games.js — the games, the subjects the
// lair's front door sorts by, the skill tags, and which games are paid — so the
// iOS lair lists the same games, in the same order, without hand-copying them.
// Re-run whenever games.js (or the operation labels in operations.js) changes:
//
//   npm run ios:game-catalog
//
// Deterministic. src/data/games.swift.test.js renders the catalog again and
// fails when the committed Swift file is stale.

import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { GAME_TYPES, SUBJECTS, SKILL_TAGS, PAID_GAME_IDS } from '../src/data/games.js';
import { OPERATION_BY_KEY } from '../src/data/operations.js';

export const SWIFT_CATALOG_PATH = resolve(
  dirname(fileURLToPath(import.meta.url)),
  '..', 'ios', 'Packages', 'GameRules', 'Sources', 'GameRules', 'LairCatalog.swift',
);

// JSON string escaping is valid Swift string-literal escaping for the
// characters that can appear here (quotes, backslashes, emoji).
const str = value => JSON.stringify(value);
const strings = values => `[${values.map(str).join(', ')}]`;
const color = hex => `0x${hex.replace('#', '').toUpperCase()}`;

export function renderSwiftGameCatalog() {
  const subjects = SUBJECTS.map(s => [
    '        LairSubject(',
    `            id: ${str(s.key)}, label: ${str(s.label)}, emoji: ${str(s.emoji)},`,
    `            blurb: ${str(s.blurb)}, color: ${color(s.color)}),`,
  ].join('\n'));

  // An operation's blurb ("times tables") captions its card in the facts
  // picker; the literacy tags have none.
  const tags = SKILL_TAGS.map(t => [
    `        LairSkillTag(id: ${str(t.key)}, label: ${str(t.label)}, symbol: ${str(t.symbol)},`,
    `                     blurb: ${str(OPERATION_BY_KEY[t.key]?.blurb ?? '')}, color: ${color(t.color)}),`,
  ].join('\n'));

  const games = GAME_TYPES.map(g => [
    '        LairGame(',
    `            id: ${str(g.id)}, subject: ${str(g.subject)}, name: ${str(g.name)}, emoji: ${str(g.emoji)},`,
    `            description: ${str(g.description)},`,
    `            skills: [${g.skills.map(k => `.${k}`).join(', ')}], practices: ${strings(g.practices)},`,
    `            hasOwnPage: ${Boolean(g.route)}, premium: ${PAID_GAME_IDS.includes(g.id)}),`,
  ].join('\n'));

  return `// GENERATED by scripts/generate-swift-game-catalog.mjs from
// src/data/games.js — do not edit by hand. Run
// \`npm run ios:game-catalog\` after changing the JavaScript catalog.

extension LairSubject {
    /// The lair's front door, in the JavaScript \`SUBJECTS\` order.
    public static let all: [LairSubject] = [
${subjects.join('\n')}
    ]
}

extension LairSkillTag {
    /// Every skill tag, in the JavaScript \`SKILL_TAGS\` order.
    public static let all: [LairSkillTag] = [
${tags.join('\n')}
    ]
}

extension LairGame {
    /// Every lair game, in the JavaScript \`GAME_TYPES\` order. \`premium\` is
    /// membership of \`PAID_GAME_IDS\`.
    public static let all: [LairGame] = [
${games.join('\n')}
    ]
}
`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writeFileSync(SWIFT_CATALOG_PATH, renderSwiftGameCatalog());
  console.log(`wrote ${SWIFT_CATALOG_PATH}`);
}
