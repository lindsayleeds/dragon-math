#!/usr/bin/env node
//
// Writes ios/DragonAcademy/Fonts/FontThemeCatalog.swift from the font combos in
// src/data/fontThemes.js — each theme's id, label and its display and body
// families — so the iOS Settings picker offers the same themes, in the same
// order, with the same ids the server stores in users.font. Re-run whenever
// fontThemes.js changes:
//
//   npm run ios:font-themes
//
// A family is referenced by name as a `FontFamily` static (e.g. 'Patrick Hand'
// → `.patrickHand`), so a theme using a family the app doesn't bundle yet
// fails to compile until ios/DragonAcademy/Fonts/FontFamilies.swift has it.
//
// Deterministic. src/data/fontThemes.swift.test.js renders the catalog again
// and fails when the committed Swift file is stale.

import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { FONT_THEMES, DEFAULT_FONT_THEME } from '../src/data/fontThemes.js';

export const SWIFT_FONT_THEMES_PATH = resolve(
  dirname(fileURLToPath(import.meta.url)),
  '..', 'ios', 'DragonAcademy', 'Fonts', 'FontThemeCatalog.swift',
);

// JSON string escaping is valid Swift string-literal escaping here.
const str = value => JSON.stringify(value);

// The first family of a CSS font-family stack: "'Baloo 2', cursive" → "Baloo 2".
export function primaryFamily(stack) {
  const first = stack.split(',')[0].trim();
  return first.replace(/^['"]|['"]$/g, '');
}

// "Patrick Hand" → "patrickHand", "Baloo 2" → "baloo2".
export function familyIdentifier(family) {
  const words = family.split(/[^A-Za-z0-9]+/).filter(Boolean);
  return words
    .map((w, i) => (i === 0 ? w.toLowerCase() : w[0].toUpperCase() + w.slice(1).toLowerCase()))
    .join('');
}

export function renderSwiftFontThemes() {
  const themes = FONT_THEMES.map(t => [
    '        FontTheme(',
    `            id: ${str(t.id)}, label: ${str(t.label)},`,
    `            display: .${familyIdentifier(primaryFamily(t.display))}, body: .${familyIdentifier(primaryFamily(t.body))}),`,
  ].join('\n'));

  return `// GENERATED by scripts/generate-swift-font-themes.mjs from
// src/data/fontThemes.js — do not edit by hand. Run
// \`npm run ios:font-themes\` after changing the JavaScript themes.

extension FontTheme {
    /// Every theme, in the JavaScript \`FONT_THEMES\` order (the picker's).
    static let all: [FontTheme] = [
${themes.join('\n')}
    ]

    /// \`DEFAULT_FONT_THEME\`: the theme for a profile that never chose one.
    static let defaultID = ${str(DEFAULT_FONT_THEME)}
}
`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writeFileSync(SWIFT_FONT_THEMES_PATH, renderSwiftFontThemes());
  console.log(`wrote ${SWIFT_FONT_THEMES_PATH}`);
}
