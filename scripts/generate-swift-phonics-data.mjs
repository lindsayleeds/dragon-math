#!/usr/bin/env node
//
// Writes ios/Packages/GameRules/Sources/GameRules/PhonicsData.swift from the
// Dragon Phonics data — the curriculum's elements and stages
// (src/data/phonicsCurriculum.js), the four game modes and the round size
// (src/data/phonicsRounds.js), and Missing Sound's word levels
// (src/data/phonicsWords.js) — in the JavaScript order, which is the order a
// round's weighted pick and shuffles start from, so the app deals the same
// rounds offline without hand-copying 102 sounds. Each element's `key` is also
// the name of its bundled clip (public/audio/phonics/<key>.mp3). Re-run
// whenever any of those files changes:
//
//   npm run ios:phonics-data
//
// Deterministic. src/data/phonicsData.swift.test.js renders the file again and
// fails when the committed Swift file is stale.

import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { PHONICS_ELEMENTS, PHONICS_STAGES } from '../src/data/phonicsCurriculum.js';
import { PHONICS_MODES, ROUND_MODES, QUESTIONS_PER_ROUND } from '../src/data/phonicsRounds.js';
import { PHONICS_LEVELS, WORDS_PER_ROUND, PHONICS_CUES } from '../src/data/phonicsWords.js';

export const SWIFT_PHONICS_DATA_PATH = resolve(
  dirname(fileURLToPath(import.meta.url)),
  '..', 'ios', 'Packages', 'GameRules', 'Sources', 'GameRules', 'PhonicsData.swift',
);

// JSON string escaping is valid Swift string-literal escaping for the
// characters that appear here (letters, slashes, emoji, combining marks).
const str = value => JSON.stringify(value);
const strings = values => `[${values.map(str).join(', ')}]`;

export function renderSwiftPhonicsData() {
  const elements = PHONICS_ELEMENTS.map(el => [
    `        PhonicsElement(`,
    `            key: ${str(el.key)}, g: ${str(el.g)}, sound: ${str(el.sound)}, type: ${str(el.type)}, stage: ${el.stage},`,
    `            words: ${strings(el.words)}, near: ${strings(el.near)}, accepts: ${strings(el.accepts)},`,
    `            note: ${str(el.note)}),`,
  ].join('\n'));

  const stages = PHONICS_STAGES.map(s =>
    `        PhonicsStage(stage: ${s.stage}, label: ${str(s.label)}, emoji: ${str(s.emoji)}, blurb: ${str(s.blurb)}),`);

  const modes = PHONICS_MODES.map(m => [
    `        PhonicsMode(`,
    `            key: ${str(m.key)}, name: ${str(m.name)}, emoji: ${str(m.emoji)}, tagline: ${str(m.tagline)},`,
    `            blurb: ${str(m.blurb)},`,
    `            difficulty: ${str(m.difficulty)}, skill: ${str(m.skill)}),`,
  ].join('\n'));

  const levels = PHONICS_LEVELS.map(l => [
    `        PhonicsLevel(`,
    `            key: ${str(l.key)}, label: ${str(l.label)}, emoji: ${str(l.emoji)}, options: ${l.options},`,
    `            blurb: ${str(l.blurb)},`,
    '            words: [',
    ...l.words.map(w => `                PhonicsWordEntry(graphemes: ${strings(w.g)}, blank: ${w.b}),`),
    '            ]),',
  ].join('\n'));

  const cues = Object.entries(PHONICS_CUES).map(([g, word]) => `        ${str(g)}: ${str(word)},`);

  return `// GENERATED by scripts/generate-swift-phonics-data.mjs from
// src/data/phonicsCurriculum.js, phonicsRounds.js and phonicsWords.js — do not
// edit by hand. Run \`npm run ios:phonics-data\` after changing them.

extension PhonicsElement {
    /// Every element, in the JavaScript \`PHONICS_ELEMENTS\` order.
    public static let all: [PhonicsElement] = [
${elements.join('\n')}
    ]
}

extension PhonicsStage {
    /// The eight stages, in \`PHONICS_STAGES\` order.
    public static let all: [PhonicsStage] = [
${stages.join('\n')}
    ]
}

extension PhonicsMode {
    /// The four games, in the \`PHONICS_MODES\` order the web's picker shows.
    public static let all: [PhonicsMode] = [
${modes.join('\n')}
    ]
}

extension Phonics {
    /// Questions in a round (\`QUESTIONS_PER_ROUND\`).
    public static let questionsPerRound = ${QUESTIONS_PER_ROUND}

    /// The modes \`buildRound\` deals for (\`ROUND_MODES\`).
    public static let roundModes: [String] = ${strings(ROUND_MODES)}
}

extension PhonicsLevel {
    /// Missing Sound's levels, in \`PHONICS_LEVELS\` order.
    public static let all: [PhonicsLevel] = [
${levels.join('\n')}
    ]

    /// Words in a Missing Sound round (\`WORDS_PER_ROUND\`).
    public static let wordsPerRound = ${WORDS_PER_ROUND}
}

extension PhonicsWords {
    /// Missing Sound's "as in …" example for each tile (\`PHONICS_CUES\`).
    public static let cues: [String: String] = [
${cues.join('\n')}
    ]
}
`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writeFileSync(SWIFT_PHONICS_DATA_PATH, renderSwiftPhonicsData());
  console.log(`wrote ${SWIFT_PHONICS_DATA_PATH}`);
}
